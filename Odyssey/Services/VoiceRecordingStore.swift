import Foundation
import os

private let voiceStoreLogger = Logger(subsystem: "com.johnlarkin.Odyssey", category: "VoiceRecordingStore")

/// On-device storage for voice journal recordings.
///
/// Recordings are plain files in a `VoiceRecordings/` folder in the App Group container.
/// `DailyEntry.voiceAudioFilenames` holds only their names, so the audio never passes through
/// SwiftData or CloudKit: recordings stay on this device (and in its device backups) even when
/// iCloud sync is on.
struct VoiceRecordingStore {
    static let directoryName = "VoiceRecordings"

    /// The folder recordings live in.
    let directory: URL

    /// The store in the App Group container, falling back to Application Support when the
    /// group container isn't available (e.g. unit tests without the entitlement).
    static var shared: VoiceRecordingStore {
        let fileManager = FileManager.default
        let base = fileManager.containerURL(forSecurityApplicationGroupIdentifier: DataContainer.appGroupID)
            ?? fileManager.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return VoiceRecordingStore(directory: base.appendingPathComponent(directoryName, isDirectory: true))
    }

    /// The file URL for a stored recording's name.
    func url(for filename: String) -> URL {
        // Names are generated by `importRecording`; strip any path so a bad value can't escape.
        directory.appendingPathComponent((filename as NSString).lastPathComponent, isDirectory: false)
    }

    func exists(_ filename: String) -> Bool {
        FileManager.default.fileExists(atPath: url(for: filename).path)
    }

    /// Moves a finished recording into the store and returns the name to save on the entry.
    /// The source file is consumed.
    func importRecording(from sourceURL: URL) throws -> String {
        try ensureDirectory()
        let ext = sourceURL.pathExtension.isEmpty ? "m4a" : sourceURL.pathExtension
        let filename = "\(UUID().uuidString).\(ext)"
        let destination = url(for: filename)
        try FileManager.default.moveItem(at: sourceURL, to: destination)
        try FileManager.default.setAttributes(
            [.protectionKey: FileProtectionType.completeUntilFirstUserAuthentication],
            ofItemAtPath: destination.path
        )
        return filename
    }

    /// Deletes one recording. Missing files are fine: the goal is for the file to be gone.
    func delete(_ filename: String) {
        let fileURL = url(for: filename)
        guard FileManager.default.fileExists(atPath: fileURL.path) else { return }
        do {
            try FileManager.default.removeItem(at: fileURL)
        } catch {
            voiceStoreLogger.error("Failed to delete voice recording \(filename): \(error)")
        }
    }

    /// Deletes every recording attached to `entry`. Call before deleting the entry itself.
    func deleteRecordings(for entry: DailyEntry) {
        for filename in entry.voiceAudioFilenames ?? [] {
            delete(filename)
        }
    }

    private func ensureDirectory() throws {
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    }
}
